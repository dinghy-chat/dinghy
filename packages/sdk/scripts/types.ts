// Writes src/openapi.ts, the SDK's types, from the server's OpenAPI file, so they cannot drift.
// Run it after a change to apps/server/openapi.json: node packages/sdk/scripts/types.ts
// With --check, it writes nothing and fails when the file differs.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const SOURCE = new URL("../../../apps/server/openapi.json", import.meta.url);
const TYPES_FILE = new URL("../src/openapi.ts", import.meta.url);
// The security schemes a workspace API key can satisfy. The SDK covers only these routes.
const KEY_SCHEMES = new Set(["apiKey", "setupKey"]);
const HEADER = "// Generated by scripts/types.ts from apps/server/openapi.json. Do not edit.\n\n";

interface Operation {
  security?: Record<string, unknown>[];
}
interface Document {
  paths: Record<string, Record<string, Operation | unknown>>;
}

const isOperation = (value: unknown): value is Operation =>
  typeof value === "object" && value !== null && "responses" in value;

const keyMayCall = (operation: Operation) =>
  (operation.security ?? []).some((scheme) =>
    Object.keys(scheme).some((name) => KEY_SCHEMES.has(name)),
  );

/** The document with only the operations a key may call, and the paths that keep one. */
function keyRoutes(document: Document): Document {
  const paths: Document["paths"] = {};
  for (const [path, item] of Object.entries(document.paths)) {
    const kept = Object.entries(item).filter(
      ([, value]) => !isOperation(value) || keyMayCall(value),
    );
    if (kept.some(([, value]) => isOperation(value))) paths[path] = Object.fromEntries(kept);
  }
  return { ...document, paths };
}

function format(source: string): string {
  const biome = createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome");
  return execFileSync(
    process.execPath,
    [biome, "format", `--stdin-file-path=${fileURLToPath(TYPES_FILE)}`],
    {
      input: source,
      encoding: "utf8",
    },
  );
}

/** The text of src/openapi.ts for the current OpenAPI file. */
async function generateTypes(): Promise<string> {
  const document = JSON.parse(readFileSync(SOURCE, "utf8")) as Document;
  const ast = await openapiTS(JSON.stringify(keyRoutes(document)));
  return format(HEADER + astToString(ast));
}

const types = await generateTypes();
if (!process.argv.includes("--check")) {
  writeFileSync(TYPES_FILE, types);
} else if (readFileSync(TYPES_FILE, "utf8") !== types) {
  console.error("src/openapi.ts is out of date. Run node packages/sdk/scripts/types.ts");
  process.exitCode = 1;
}
